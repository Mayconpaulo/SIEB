function makeDeterministicPersonnelId(rank: string, fullName: string, index: number): string {
  const rankSlug = rank
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '')
    .slice(0, 8);
  const nameSlug = fullName
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 60);
  const idx = String(index + 1).padStart(3, '0');
  return `efv_${rankSlug}_${idx}_${nameSlug}`.slice(0, 96);
}

